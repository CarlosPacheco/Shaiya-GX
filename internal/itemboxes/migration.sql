CREATE TABLE PS_GameDefs_ItemBoxes (
    "Index" INTEGER PRIMARY KEY CHECK ("Index" BETWEEN 1 AND 32767),
    Description TEXT NOT NULL,
    BoxType INTEGER NOT NULL CHECK (BoxType IN (1, 2)),
    ItemType INTEGER NOT NULL CHECK (ItemType IN (1, 2))
) STRICT;

CREATE TABLE PS_GameDefs_ItemBoxRewards (
    BoxIndex INTEGER NOT NULL REFERENCES PS_GameDefs_ItemBoxes("Index") ON DELETE CASCADE,
    Position INTEGER NOT NULL CHECK (Position > 0),
    Item INTEGER NOT NULL CHECK (Item BETWEEN 1 AND 2147483647),
    Chance INTEGER NOT NULL CHECK (Chance BETWEEN 0 AND 10000000000),
    PRIMARY KEY (BoxIndex, Position)
) STRICT;

