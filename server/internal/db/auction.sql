CREATE TABLE GX_Auctions (
 ID INTEGER PRIMARY KEY AUTOINCREMENT, Seller INTEGER NOT NULL, Request TEXT NOT NULL,
 SellerName TEXT NOT NULL, Name TEXT NOT NULL, Category INTEGER NOT NULL,
 ItemType INTEGER NOT NULL, TypeID INTEGER NOT NULL, Level INTEGER NOT NULL,
 Item BLOB NOT NULL, ItemUID INTEGER UNIQUE, Price INTEGER NOT NULL CHECK(Price >= 500), Buyout INTEGER NOT NULL CHECK(Buyout > Price AND Buyout <= 4000000000),
 Deposit INTEGER NOT NULL CHECK(Deposit > 0), Bidder INTEGER NOT NULL DEFAULT 0,
 Ends INTEGER NOT NULL, State TEXT NOT NULL DEFAULT 'active', Version INTEGER NOT NULL DEFAULT 1, UNIQUE(Seller,Request)
) STRICT;
CREATE INDEX GX_AuctionEnds ON GX_Auctions(State, Ends);
CREATE INDEX GX_AuctionCategory ON GX_Auctions(State, Category, ID);
CREATE INDEX GX_AuctionItem ON GX_Auctions(State, ItemType, TypeID, ID);
CREATE INDEX GX_AuctionSeller ON GX_Auctions(Seller, State, ID);
CREATE INDEX GX_AuctionBidder ON GX_Auctions(Bidder, State, ID);
CREATE TABLE GX_AuctionClaims (
 ID INTEGER PRIMARY KEY AUTOINCREMENT, Auction INTEGER NOT NULL REFERENCES GX_Auctions(ID),
 Owner INTEGER NOT NULL, Gold INTEGER NOT NULL CHECK(Gold BETWEEN 0 AND 4294967295), Reason TEXT NOT NULL,
 Ends INTEGER NOT NULL, Claimed INTEGER NOT NULL DEFAULT 0
) STRICT;
CREATE INDEX GX_AuctionClaimOwner ON GX_AuctionClaims(Owner, Claimed, Gold, ID);
CREATE UNIQUE INDEX GX_AuctionOneItem ON GX_AuctionClaims(Auction) WHERE Gold=0;
CREATE TABLE GX_AuctionWatch (
 Owner INTEGER NOT NULL, Auction INTEGER NOT NULL REFERENCES GX_Auctions(ID),
 PRIMARY KEY(Owner,Auction)
) STRICT;
