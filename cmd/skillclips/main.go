// Command skillclips writes internal/skilltiming/clips_gen.go: how long each
// instant skill's own animation runs (30 fps), so the server can keep the next
// action waiting for it like the original client does (0x40ff40). Animations
// never change, so the table is generated once from the client data.
//
//	go run ./cmd/skillclips -data "Shaiya GX/data" -out internal/skilltiming/clips_gen.go
package main

import (
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Spelunkern/Shaiya-GX/internal/data/model"
	"github.com/Spelunkern/Shaiya-GX/internal/data/sdata"
	"github.com/Spelunkern/Shaiya-GX/internal/scene"
)

func main() {
	dataDir := flag.String("data", "", "client data directory (contains Character/)")
	out := flag.String("out", "", "generated Go file")
	flag.Parse()
	if *dataDir == "" || *out == "" {
		log.Fatal("-data and -out required")
	}
	raw, err := os.ReadFile(filepath.Join(*dataDir, "Character", "Skill.SData"))
	if err != nil {
		log.Fatal(err)
	}
	defs, err := sdata.ParseSkills(raw)
	if err != nil {
		log.Fatal(err)
	}
	// Shortest valid clip per ALT slot across every race and sex, so the server
	// never holds back what some legitimate client would allow.
	slots := map[int]float64{}
	files, _ := filepath.Glob(filepath.Join(*dataDir, "Character", "*", "*_action.alt"))
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		acts, err := model.ParseALT(b)
		if err != nil {
			continue
		}
		folder := filepath.Dir(f)
		for slot, act := range acts {
			name := path.Base(strings.ReplaceAll(act.Name, "\\", "/"))
			// Slots without their own skill clip fall back to the select pose.
			if act.Name == "" || strings.Contains(strings.ToLower(name), "019_select") {
				continue
			}
			ab, err := os.ReadFile(filepath.Join(folder, "ANI", name))
			if err != nil {
				continue
			}
			an, err := model.ParseANI(ab)
			if err != nil || an.End <= an.Start {
				continue
			}
			seconds := float64(an.End-an.Start) / 30
			if old, ok := slots[slot]; !ok || seconds < old {
				slots[slot] = seconds
			}
		}
	}
	type row struct {
		key uint32
		ms  uint16
	}
	var rows []row
	for key, d := range defs {
		if d.ReadyTime > 0 || d.Effect == 0 {
			continue
		}
		// Weapon swings (attack 1/2 without a skill clip) follow the basic cadence.
		slot := scene.SkillAction(d.Animation, d.Attack, d.Effect, 0, 0)
		if slot != 87 && slot != 90 && slot != 93 && (slot < 100 || slot > 110) {
			continue
		}
		if s, ok := slots[slot]; ok && s > 0 {
			rows = append(rows, row{uint32(key.ID)<<8 | uint32(key.Level), uint16(s * 1000)})
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].key < rows[j].key })
	var b strings.Builder
	b.WriteString("// Code generated by cmd/skillclips; DO NOT EDIT.\n\npackage skilltiming\n\n")
	b.WriteString("// clipMilliseconds maps skillID<<8|level to the shortest own clip of that skill.\n")
	b.WriteString("var clipMilliseconds = map[uint32]uint16{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%#x: %d,\n", r.key, r.ms)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d skills\n", len(rows))
}
